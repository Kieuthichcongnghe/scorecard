CREATE TABLE STG_TEST_APP AS
SELECT 
		SK_ID_CURR
--	,	TARGET
	,	CODE_GENDER
	,	FLAG_OWN_CAR
	,	FLAG_OWN_REALTY
	,	CNT_CHILDREN
	,	AMT_INCOME_TOTAL
	,	AMT_CREDIT
	,	AMT_ANNUITY
	,	AMT_GOODS_PRICE
	,	DAYS_BIRTH
	,	DAYS_EMPLOYED
	,	DAYS_REGISTRATION
	,	DAYS_ID_PUBLISH
	,	OWN_CAR_AGE
	,	-DAYS_BIRTH / 365 AS AGE_YEARS
	,	CASE WHEN DAYS_EMPLOYED = 365243 THEN NULL ELSE (-1* DAYS_EMPLOYED)/365 end AS EMPLOYED_YEARS
	,	CASE WHEN DAYS_EMPLOYED = 365243 THEN 1 ELSE 0 end AS flag_days_employed_anom
	,	EXT_SOURCE_1
	,	EXT_SOURCE_2
	,	EXT_SOURCE_3
	,	(COALESCE(EXT_SOURCE_1,0) + COALESCE(EXT_SOURCE_2,0) + COALESCE(EXT_SOURCE_3,0)) / 
			NULLIF((CASE WHEN EXT_SOURCE_1 IS NOT NULL THEN 1 ELSE 0 END 
					+ CASE WHEN EXT_SOURCE_2 IS NOT NULL THEN 1 ELSE 0 END 
					+ CASE WHEN EXT_SOURCE_3 IS NOT NULL THEN 1 ELSE 0 END), 0) AS EXT_SOURCE_AVG
	,	AMT_CREDIT / NULLIF(AMT_INCOME_TOTAL, 0) AS CREDIT_INCOME_RATIO
	,	AMT_ANNUITY / NULLIF(AMT_INCOME_TOTAL, 0) AS	ANNUITY_INCOME_RATIO
	,	AMT_CREDIT / NULLIF(AMT_ANNUITY, 0) AS CREDIT_TERM_PROXY
	,	AMT_ANNUITY / NULLIF(AMT_CREDIT, 0) AS ANNUITY_CREDIT_RATIO
	,	AMT_GOODS_PRICE / NULLIF(AMT_CREDIT, 0) AS LTV_RATIO
	,	AMT_GOODS_PRICE / NULLIF(AMT_INCOME_TOTAL, 0) AS GOODS_INCOME_RATIO
	,	(CASE WHEN DAYS_EMPLOYED = 365243 THEN NULL ELSE (-DAYS_EMPLOYED) END) / NULLIF(DAYS_BIRTH, 0) AS employed_to_age_ratio
	,	AMT_INCOME_TOTAL / NULLIF(CNT_FAM_MEMBERS, 0) AS income_per_family_member
	,	CNT_CHILDREN / NULLIF(CNT_FAM_MEMBERS, 0) AS children_ratio
FROM APPLICATION_TEST

